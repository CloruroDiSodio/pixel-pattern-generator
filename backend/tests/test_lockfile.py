"""Tests that keep the deployment artifacts consistent with the code."""

from __future__ import annotations

import re
from pathlib import Path

import pytest

BACKEND = Path(__file__).resolve().parent.parent
LOCK = BACKEND / "requirements.lock"
REQUIREMENTS = BACKEND / "requirements.txt"


def _declared_pins() -> dict[str, str]:
    """``{package: version}`` for every exact pin in requirements.txt."""
    pins = re.findall(
        r"^([A-Za-z0-9_.-]+)(?:\[[^\]]+\])?==([0-9][^\s;#]*)",
        REQUIREMENTS.read_text(),
        re.MULTILINE,
    )
    return {name.lower(): version for name, version in pins}


def _locked_version(package: str) -> str | None:
    # pip-compile records extras inline: ``uvicorn[standard]==0.54.0``.
    match = re.search(
        rf"^{re.escape(package)}(?:\[[^\]]+\])?==([^\s\;]+)",
        LOCK.read_text(),
        re.MULTILINE | re.IGNORECASE,
    )
    return match.group(1) if match else None


class TestPinnedLockFile:
    """`requirements.lock` is what Render installs with `--require-hashes`.

    It is compiled on a single interpreter (Python 3.12, the deploy target) and
    must stay in step with requirements.txt, or the deploy silently runs a
    different dependency set from the one CI tested.
    """

    def test_lock_file_exists(self) -> None:
        assert LOCK.is_file(), "requirements.lock is missing"

    def test_lock_is_compiled_for_a_supported_python(self) -> None:
        header = re.search(r"autogenerated by pip-compile with Python (\d+)\.(\d+)", LOCK.read_text())
        assert header, "requirements.lock has no pip-compile header"
        assert (int(header.group(1)), int(header.group(2))) >= (3, 10), (
            "requirements.lock was compiled on Python < 3.10, which is no longer supported"
        )

    def test_lock_has_no_python_version_branches(self) -> None:
        # A marker branch is skipped on hosts that do not match it - that is how
        # Pillow once went missing on the 3.12 Render host. One interpreter, one set.
        assert "python_version" not in LOCK.read_text()

    def test_lock_matches_requirements(self) -> None:
        declared = _declared_pins()
        assert declared, "requirements.txt has no exact pins"
        for package, version in declared.items():
            assert _locked_version(package) == version, (
                f"requirements.txt pins {package}=={version} but requirements.lock has "
                f"{_locked_version(package)} - re-run pip-compile"
            )

    def test_pillow_is_the_patched_release(self) -> None:
        # CVE-2026-25990 (out-of-bounds write decoding PSD) is fixed in 12.1.1.
        version = _locked_version("pillow")
        assert version, "pillow is not locked"
        major, minor, patch = (int(part) for part in version.split(".")[:3])
        assert (major, minor, patch) >= (12, 1, 1), (
            f"requirements.lock resolves to Pillow {version}, which is inside the "
            "CVE-2026-25990 range (fixed in 12.1.1)"
        )

    @pytest.mark.parametrize(
        "package", ["fastapi", "uvicorn", "python-multipart", "pydantic", "pillow"]
    )
    def test_runtime_dependencies_are_locked_and_hashed(self, package: str) -> None:
        text = LOCK.read_text()
        pinned = re.search(
            rf"^{re.escape(package)}(\[[^\]]+\])?==[^\n]*\\\n\s+--hash=sha256:",
            text,
            re.MULTILINE,
        )
        assert pinned, f"{package} is not locked with hashes - run pip-compile --generate-hashes"
